// Copies the self-hosted fonts from node_modules into vendor/fonts and writes css/fonts.css.
// Usage: node tools/build-fonts.mjs   (only needed again if the font versions change)
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';

mkdirSync('vendor/fonts', { recursive: true });
let out = '/* Self-hosted fonts (@fontsource/inter 5.3.0, @fontsource/playfair-display 5.3.0, SIL Open Font License).\n   latin + latin-ext subsets; the browser fetches latin-ext only for characters such as the rupee sign. */\n';
for (const [pkg, family, weights] of [['inter', 'Inter', [400, 500, 600, 700]], ['playfair-display', 'Playfair Display', [400, 500, 600]]]) {
  for (const w of weights) {
    const css = readFileSync(`node_modules/@fontsource/${pkg}/${w}.css`, 'utf8');
    for (const sub of ['latin-ext', 'latin']) {
      const block = css.split(`/* ${pkg}-${sub}-${w}-normal */`)[1];
      if (!block) throw new Error(`missing ${pkg} ${sub} ${w}`);
      const range = block.match(/unicode-range:\s*([^;]+);/)[1].trim();
      const file = `${pkg}-${sub}-${w}-normal.woff2`;
      copyFileSync(`node_modules/@fontsource/${pkg}/files/${file}`, `vendor/fonts/${file}`);
      out += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:swap;src:url(../vendor/fonts/${file}) format("woff2");unicode-range:${range}}\n`;
    }
  }
}
// written into css/styles.css between the fonts markers (one stylesheet = fewer render-blocking requests)
const styles = readFileSync('css/styles.css', 'utf8');
const START = '/* fonts:start (generated by tools/build-fonts.mjs) */', END = '/* fonts:end */';
const a = styles.indexOf(START), b = styles.indexOf(END);
if (a < 0 || b < a) throw new Error('fonts markers not found in css/styles.css');
writeFileSync('css/styles.css', styles.slice(0, a) + START + '\n' + out + styles.slice(b));
console.log('fonts written into css/styles.css');
